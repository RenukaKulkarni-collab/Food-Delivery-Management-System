---26. Top 2 customers by spending in each restaurant

with CustomersSpending
As
(
select u.User_ID,u.First_Name,r.restaurant_ID,r.restaurant_Name,sum(o.Total_Amount) as Total_Spending
from Users u
inner join Orders o
on u.User_ID=o.User_ID
inner join Restaurants r
on o.Restaurant_ID=r.Restaurant_ID 
GROUP BY
        u.User_ID,
        u.First_Name,
        r.Restaurant_ID,
        r.Restaurant_Name
),
RankedCustomer
AS
(
select *,
DENSE_RANK()over(partition by restaurant_ID order by Total_Spending desc) as rn
from CustomersSpending
)
SELECT
    User_ID,
    First_Name,
    restaurant_ID,
    restaurant_Name,
    Total_Spending,
    rn
FROM RankedCustomer
WHERE rn <=2
ORDER BY Restaurant_ID,rn;


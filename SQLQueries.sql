---30.Find customers who placed more orders than the average customer
with CustomerOrders
AS
(
select u.user_ID,u.First_Name,count(o.Order_ID) as Total_orders
from Users u 
inner join Orders o
on u.User_ID=o.User_ID
GROUP BY
        u.User_ID,
        u.First_Name
),
AverageOrders AS
(
    SELECT AVG(CAST(Total_Orders AS DECIMAL(10,2))) AS Avg_Orders
    FROM CustomerOrders
)
SELECT
    c.User_ID,
    c.First_Name,
    c.Total_Orders,
    a.Avg_Orders
FROM CustomerOrders c
CROSS JOIN AverageOrders a
WHERE c.Total_Orders > a.Avg_Orders;


